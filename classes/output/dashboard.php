namespace block_le_hub_dashboard\output;

use renderer_base;

/**
 * The block's content: the dashboard for the current user, as they last left it.
 *
 * @package    block_le_hub_dashboard
 * @copyright  2026 Pierre Camaly de Brosses - University of Exeter
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class dashboard implements \renderable, \templatable {
    /** @var int */
    protected int $userid;

    /**
     * Constructor.
     *
     * @param int $userid
     */
    public function __construct(int $userid) {
        $this->userid = $userid;
    }

    #[\Override]
    public function export_for_template(renderer_base $output): array {
        return (new \block_le_hub_dashboard\local\dashboard($this->userid))->export();
    }
}
